"use client"

import { Lightbulb } from "lucide-react"
import { Button } from "@/components/ui/button"
import { Card, CardContent, CardDescription, CardHeader, CardTitle } from "@/components/ui/card"
import { recommendations } from "@/lib/edith-data"
import { cn } from "@/lib/utils"

const severityStyles = {
  critical: "bg-[#FDE8E6] text-[#B42318] border border-[#D64545]/30",
  medium: "bg-[#FFF1D6] text-[#8A5A00] border border-[#D99A1E]/30",
  low: "bg-[#ECE8FF] text-[#5B35F5] border border-[#5B35F5]/30",
}

interface RecommendationsViewProps {
  dismissed: string[]
  onApply: (id: string, title: string) => void
}

export function RecommendationsView({ dismissed, onApply }: RecommendationsViewProps) {
  const items = recommendations.filter((r) => !dismissed.includes(r.id))

  return (
    <Card className="rounded-[20px] border border-[#E6E1FA] bg-white shadow-none">
      <CardHeader className="border-b border-[#EEEAFB] pb-4">
        <CardTitle className="flex items-center gap-2 text-base font-bold text-[#15122B]">
          <Lightbulb className="size-4 text-[#5B35F5]" aria-hidden="true" />
          Security Recommendations
        </CardTitle>
        <CardDescription className="text-xs text-[#5E5A7A]">Suggested actions generated by the heuristics engine.</CardDescription>
      </CardHeader>
      <CardContent className="space-y-3 pt-4">
        {items.length === 0 && (
          <p className="py-8 text-center text-sm text-[#5E5A7A]">All recommendations applied.</p>
        )}
        {items.map((rec) => (
          <div
            key={rec.id}
            className="flex flex-col gap-3 rounded-[16px] border border-[#E6E1FA] bg-[#F9F8FF] p-4 transition-colors hover:bg-white sm:flex-row sm:items-center justify-between"
          >
            <div className="min-w-0 flex-1">
              <div className="flex items-center gap-2">
                <span
                  className={cn(
                    "rounded-full px-2.5 py-0.5 text-[10px] font-bold uppercase tracking-wider",
                    severityStyles[rec.severity],
                  )}
                >
                  {rec.severity}
                </span>
                <h3 className="text-sm font-semibold text-[#15122B]">{rec.title}</h3>
              </div>
              <p className="mt-1 text-xs text-[#5E5A7A]">{rec.detail}</p>
            </div>
            <Button
              variant="outline"
              size="sm"
              onClick={() => onApply(rec.id, rec.title)}
              className="rounded-full border border-[#E6E1FA] bg-white hover:bg-[#F9F8FF] text-[#15122B] text-xs font-semibold h-[34px] px-4"
            >
              Apply fix
            </Button>
          </div>
        ))}
      </CardContent>
    </Card>
  )
}
