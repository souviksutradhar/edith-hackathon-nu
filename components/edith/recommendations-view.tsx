"use client"

import { Lightbulb } from "lucide-react"
import { Button } from "@/components/ui/button"
import { Card, CardContent, CardDescription, CardHeader, CardTitle } from "@/components/ui/card"
import { recommendations } from "@/lib/edith-data"
import { cn } from "@/lib/utils"

const severityStyles = {
  critical: "bg-danger/15 text-danger",
  medium: "bg-warning/15 text-warning",
  low: "bg-info/15 text-info",
}

interface RecommendationsViewProps {
  dismissed: string[]
  onApply: (id: string, title: string) => void
}

export function RecommendationsView({ dismissed, onApply }: RecommendationsViewProps) {
  const items = recommendations.filter((r) => !dismissed.includes(r.id))

  return (
    <Card className="border border-border bg-card">
      <CardHeader>
        <CardTitle className="flex items-center gap-2 text-base">
          <Lightbulb className="size-4 text-primary" aria-hidden="true" />
          Security Recommendations
        </CardTitle>
        <CardDescription>Suggested actions generated by the heuristics engine.</CardDescription>
      </CardHeader>
      <CardContent className="space-y-3">
        {items.length === 0 && (
          <p className="py-8 text-center text-sm text-muted-foreground">All recommendations applied.</p>
        )}
        {items.map((rec) => (
          <div
            key={rec.id}
            className="flex flex-col gap-3 rounded-lg border border-border p-4 transition-colors hover:bg-accent/40 sm:flex-row sm:items-center"
          >
            <div className="min-w-0 flex-1">
              <div className="flex items-center gap-2">
                <span
                  className={cn(
                    "rounded-full px-2 py-0.5 text-[10px] font-bold uppercase tracking-wider",
                    severityStyles[rec.severity],
                  )}
                >
                  {rec.severity}
                </span>
                <h3 className="text-sm font-semibold">{rec.title}</h3>
              </div>
              <p className="mt-1 text-sm text-muted-foreground">{rec.detail}</p>
            </div>
            <Button variant="outline" size="sm" onClick={() => onApply(rec.id, rec.title)}>
              Apply fix
            </Button>
          </div>
        ))}
      </CardContent>
    </Card>
  )
}
